// Regenerate the dark palette from the light palette's inherited color tokens.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '../public');
const colors = new Map();
for (const file of readdirSync(root).filter(
  (name) => name.endsWith('.css') && name !== 'theme.css',
)) {
  const source = readFileSync(resolve(root, file), 'utf8');
  for (const match of source.matchAll(
    /var\(--tone-([a-f0-9]{6}(?:[a-f0-9]{2})?),\s*#[a-f0-9]+\)/gi,
  )) {
    const hex = match[1];
    const rgb = [0, 2, 4].map((index) => parseInt(hex.slice(index, index + 2), 16) / 255);
    const high = Math.max(...rgb),
      low = Math.min(...rgb),
      lightness = (high + low) / 2;
    const target = 0.97 - 0.88 * lightness;
    const scale =
      (target <= 0.5 ? target : 1 - target) / Math.max(0.001, Math.min(lightness, 1 - lightness));
    const dark = rgb.map((channel) =>
      Math.round(
        Math.max(
          0,
          Math.min(1, target + (channel - lightness) * scale * (lightness > 0.8 ? 0.18 : 0.75)),
        ) * 255,
      ),
    );
    colors.set(
      hex,
      '#' + dark.map((channel) => channel.toString(16).padStart(2, '0')).join('') + hex.slice(6),
    );
  }
}
writeFileSync(
  resolve(root, 'theme.css'),
  `/* Generated by scripts/build-theme.js. Shared by document and shadow controls. */\n:root {\n  color-scheme: light;\n}\n:root[data-theme='dark'] {\n  color-scheme: dark;\n${[
    ...colors,
  ]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  --tone-${key}: ${value};`)
    .join(
      '\n',
    )}\n}\n:root[data-theme='dark'] :is(input, textarea, select) {\n  color-scheme: dark;\n}\n`,
);
console.log(`Generated ${colors.size} dark palette tokens.`);
